import numpy as np
import matplotlib.pyplot as plt
from scipy import ndimage as ndi

img = np.load("7.npy")

#Angulos
#Cada fila es una proyección en cierto ángulo
filas, columnas = img.shape
ang = np.linspace(0., 180., filas, endpoint=False)

freqs = np.fft.fftfreq(columnas).reshape(-1, 1)
freqs_filtrada = np.abs(freqs) #elimina las frecuencias bajas

recon = np.zeros((columnas, columnas)) #Crea la matriz reconstruida de ceros
x = np.arange(-columnas//2, columnas//2)
X, Y = np.meshgrid(x, x)
coords = np.stack((X.ravel(), Y.ravel()))

for i, theta in enumerate(ang):
    proy = img[i, :] #Toma la proyección correspondiente al ángulo
    proy_fft = np.fft.fft(proy) #transformada
    proy_fft_filtrada = proy_fft * freqs_filtrada.ravel() #filtro pasa altas

    proy_filtrada = np.real(np.fft.ifft(proy_fft_filtrada))

    #Retroproyección
    #Forma la imagen ya rotada
    img_rotada = ndi.rotate(
        np.tile(proy_filtrada[:, None], columnas).T,
        -theta,
        reshape=False,
        mode="reflect"
    )
    recon += img_rotada #suma la intensidad para ese ángulo

plt.imsave("4.png", recon, cmap="gray")