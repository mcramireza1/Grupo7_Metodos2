def snr_freq1(freqs, F, freq0=5.0, df_peak=2, W_excl=10, fmin_bg=1):
  freqs = np.asarray(freqs)
  S = np.abs(F)

  peak_mask = (freqs >= freq0 - df_peak) & (freqs <= freq0 + df_peak)
  if not np.any(peak_mask):  # guardia
      return np.nan
  S_pico = S[peak_mask].max()

  bg_mask = (freqs >= fmin_bg) & ((freqs < freq0 - W_excl) | (freqs > freq0 + W_excl))
  if np.sum(bg_mask) < 5:     # guardia mínima de puntos
      # fallback: usar todo lo que no está en la ventana de búsqueda del pico
      bg_mask = ~peak_mask

  sigma_fondo = np.std(S[bg_mask])
  if sigma_fondo == 0:
      return np.nan

  SNR = S_pico / sigma_fondo
  return SNR

