def FWHM(freqs, y_ajustada):
    mitad = np.max(y_ajustada) / 2
    indices = np.where(y_ajustada >= mitad)[0]
    if len(indices) < 2:
        return np.nan
    return freqs[indices[-1]] - freqs[indices[0]]

