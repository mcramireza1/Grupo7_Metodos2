# Parámetros y condiciones iniciales indicadas en el enunciado para el sistema
alpha = 2.0
beta = 1.5
gamma = 0.3
delta = 0.4

x0 = 3.0   # decazorros
y0 = 2.0   # kiloconejos
y_init = [x0, y0]

# EcuacionesLotka-Volterra
def lotka_volterra(t, y):
    x, y_p = y
    dxdt = alpha * x - beta * x * y_p
    dydt = -gamma * y_p + delta * x * y_p
    return [dxdt, dydt]

# Intervalo de integración
t_span = (0, 50)
t_eval = np.linspace(0, 50, 1000)

# Resolver el sistema
sol = solve_ivp(lotka_volterra, t_span, y_init, t_eval=t_eval, method="DOP853")

# Graficar resultados
