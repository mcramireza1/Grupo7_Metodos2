import numpy as np
from scipy.integrate import solve_ivp
import matplotlib.pyplot as plt
import pandas as pd

def lane_emden_ivp(x, S, n):
    theta, y = S
    dtheta_dx = y
    dy_dx = -theta**n - (2/x)*y
    return [dtheta_dx, dy_dx]

def evento_primer_cero(x, S, n):
    return S[0]
evento_primer_cero.terminal = True
evento_primer_cero.direction = -1

n_values = [0.0, 1.0, 1.5, 2.0, 3.0, 4.0, 5.0]
resultados = []

fig, ax = plt.subplots(figsize=(10, 6))

for i, n in enumerate(n_values):
    x0 = 1e-6
    theta0 = 1 - (x0**2)/6
    dtheta0 = -x0/3
    S0 = [theta0, dtheta0]

    color = plt.cm.tab10(i / len(n_values))

    if n != 5.0:
        sol_ext = solve_ivp(
            lane_emden_ivp,
            [x0, 35],
            S0,
            args=(n,),
            dense_output=True,
            rtol=1e-12,
            atol=1e-12,
            max_step=0.01
        )

        sol_phys = solve_ivp(
            lane_emden_ivp,
            [x0, 35],
            S0,
            args=(n,),
            events=lambda x, S, n=n: evento_primer_cero(x, S, n),
            dense_output=True,
            rtol=1e-12,
            atol=1e-12,
            max_step=0.01
        )

        if sol_phys.t_events[0].size > 0:
            xs = sol_phys.t_events[0][0]
            theta_xs, dtheta_xs = sol_phys.sol(xs)
            M = -xs**2 * dtheta_xs
            rho_ratio = -(1/3) * xs / dtheta_xs
        else:
            xs, M, rho_ratio = np.nan, np.nan, np.nan

        resultados.append([n, xs, M, rho_ratio])


        x_phys = np.linspace(x0, xs, 300)
        y_phys = sol_phys.sol(x_phys)
        ax.plot(x_phys, y_phys[0], color=color, label=f'n = {n}')

        x_ext = np.linspace(x0, 35, 1000)
        y_ext = sol_ext.sol(x_ext)
        ax.plot(x_ext, y_ext[0], linestyle='-', color=color, alpha=0.5, label=f'n = {n}')

    else:
        # n=5
        def theta_n5(x):
            return 1.0 / np.sqrt(1 + x**2 / 3)

        x_plot = np.linspace(0, 35, 1000)
        theta_plot = theta_n5(x_plot)
        ax.plot(x_plot, theta_plot, color=color, label="n = 5 (analítico)")
        xs = np.inf
        M = np.pi * np.sqrt(3)
        rho_ratio = np.inf
        resultados.append([n, xs, M, rho_ratio])

