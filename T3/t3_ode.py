import numpy as np
import matplotlib.pyplot as plt
from scipy.integrate import solve_ivp
from joblib import Parallel, delayed

def F(t,Y, alpha):
    tetha,r,Pt,Pr = Y
    dtetha = Pt/(r+1)**2
    dr = Pr
    dPt=-(alpha**2)*np.sin(tetha)*(r+1)
    dPr= (alpha**2)*np.cos(tetha)-r+(Pt**2)/(r+1)**3
    return [dtetha,dr,dPt,dPr]

def evento(t,Y,*args):
    return Y[0]
evento.terminal = False
evento.direction = -1

tmax = 10**4
ts = np.linspace(0,tmax,400)
y0 = [np.pi/2, 0.0, 0.0, 0.0]
alphas = np.linspace(1,1.2,20)

def solucion(alpha):
    sol = solve_ivp(F, (0, tmax), y0, args=(alpha,),
                   events=evento)
    return alpha, sol.t_events, sol.y_events

res = Parallel(n_jobs=-1)(delayed(solucion)(alpha) for alpha in alphas)

