import numpy as np
import matplotlib.pyplot as plt
from scipy.integrate import solve_ivp
from scipy.optimize import minimize_scalar

# Parámetros físicos
masa = 10.01
gravedad = 9.773
A = 1.642
B = 40.624
C = 2.36

# Coeficiente beta dependiente de la altura
def beta(altura):
    return A * (1 - altura / B) ** C

# Ecuaciones del movimiento con rozamiento
def movimiento(t, estado, angulo, velocidad_inicial):
    x, y, vx, vy = estado
    velocidad = np.sqrt(vx**2 + vy**2)

    beta_valor = beta(y)
    fuerza_friccion = beta_valor * velocidad**2 / masa

    ax = -fuerza_friccion * (vx / velocidad) if velocidad > 0 else 0
    ay = -gravedad - fuerza_friccion * (vy / velocidad) if velocidad > 0 else -gravedad

    return [vx, vy, ax, ay]

# Calcula el alcance para un ángulo dado
def calcular_alcance(angulo, velocidad_inicial, tiempo=(0, 20), rtol=1e-6, atol=1e-8):
    x0, y0 = 0, 0
    vx0 = velocidad_inicial * np.cos(np.radians(angulo))
    vy0 = velocidad_inicial * np.sin(np.radians(angulo))
    estado_inicial = [x0, y0, vx0, vy0]

    def toca_suelo(t, estado, angulo, velocidad_inicial):
        return estado[1]  # condición: y = 0
    toca_suelo.terminal = True
    toca_suelo.direction = -1

    sol = solve_ivp(movimiento, tiempo, estado_inicial,
                   args=(angulo, velocidad_inicial), events=toca_suelo,
                   rtol=rtol, atol=atol, dense_output=True)

    if sol.status == 1:
        return sol.y_events[0][0][0]  # x cuando toca suelo
    else:
        return sol.y[0][-1]

# Busca el ángulo que da el máximo alcance
def angulo_optimo(velocidad_inicial, rango_angulos=(10, 80)):
    def negativo_alcance(angulo):
        return -calcular_alcance(angulo, velocidad_inicial)

    resultado = minimize_scalar(negativo_alcance, bounds=rango_angulos, method='bounded')
    angulo_mejor = resultado.x
    alcance_max = -resultado.fun

    return angulo_mejor, alcance_max

# Simulación para distintos valores de velocidad inicial
velocidades = np.linspace(10, 140, 50)
alcances_maximos = []
angulos_optimos = []

for v0 in velocidades:
    angulo_mejor, alcance_max = angulo_optimo(v0)
    angulos_optimos.append(angulo_mejor)
    alcances_maximos.append(alcance_max)
    print(f"v0 = {v0:.1f} m/s, ángulo óptimo = {angulo_mejor:.2f}°, alcance máximo = {alcance_max:.2f} m")

# Gráfica
plt.figure(figsize=(10, 6))
plt.plot(velocidades, alcances_maximos, 'b-', linewidth=2)
plt.xlabel('Velocidad inicial $v_0$ (m/s)')
plt.ylabel('Alcance máximo $x_{max}$ (m)')
plt.title('Alcance máximo vs Velocidad inicial')
plt.grid(True, alpha=0.3)
