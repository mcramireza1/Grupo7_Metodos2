plt.imshow(u, origin='lower', cmap='bone', interpolation='bilinear')
plt.axis('off')
plt.title(f"{titulo}\nα={alpha}, β={beta}, L={L}, N={N}, T≈{T}, dt≈{dt:.2e}, BC={BC}", fontsize=9)
