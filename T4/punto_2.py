import numpy as np
import matplotlib.pyplot as plt


L    = 1      # dominio [0,L]x[0,L]
N    = 150
dx   = L / N
alpha, beta = 1e-4, 0.8e-2
T    = 40.0
BC   = 'periodic'

dt_diff = (dx*dx) / (4.0*max(alpha, beta))
dt = 0.2 * dt_diff
steps = int(np.ceil(T / dt))

# ruido
rng = np.random.default_rng(0)
u = 0.1 * rng.standard_normal((N, N))
v = 0.1 * rng.standard_normal((N, N))

#Laplace
def lap(A):
    mode = 'wrap' if BC == 'periodic' else 'edge'   # periodic=torus, neumann=reflejo
    P = np.pad(A, 1, mode=mode)
    return (P[:-2,1:-1] + P[2:,1:-1] + P[1:-1,:-2] + P[1:-1,2:] - 4.0*P[1:-1,1:-1]) / (dx*dx)

for n in range(steps):
    Lu, Lv = lap(u), lap(v)
    Fu = u - u**3 - v - 0.05
    Gv = 10.0*(u - v)
    u += dt * (alpha*Lu + Fu)
    v += dt * (beta *Lv + Gv)

titulo = ""
