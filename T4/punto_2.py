import numpy as np
import matplotlib.pyplot as plt
from pde import PDE, FieldCollection, ScalarField, CartesianGrid

def run_simulation():

    alpha = 0.0028
    beta = 0.05
    F_str = "2.5*u - u**2 - v - 0.05"
    G_str = "4*(0.3*u - v)"

    eq = PDE(
        {
            "u": f"{alpha} * laplace(u) + ({F_str})",
            "v": f"{beta} * laplace(v) + ({G_str})",
        }
    )

    grid = CartesianGrid([[0, 3], [0, 3]], [200, 200])

    u = ScalarField.random_normal(grid, mean=0.5, std=0.1)
    v = ScalarField.random_normal(grid, mean=0.25, std=0.1)
    state = FieldCollection([u, v])


    sol = eq.solve(state, t_range=15, dt=0.0005, tracker=['progress'])

    pattern_description = "Patrón de Manchas"

    plt.figure(figsize=(8, 7))
    plt.imshow(sol.data[0], cmap='binary')
    plt.title(f"Patrón de Turing: {pattern_description}", fontsize=14, fontweight='bold')
    plt.colorbar(label="Concentration")


    plt.text(5, 195,
             f'$\\bf{{\\alpha}} = {alpha}$\n$\\bf{{\\beta}} = {beta}$',
             color='deepskyblue', fontsize=11, verticalalignment='bottom')

    plt.text(5, 5,
             f'$\\bf{{F(u,v)}} = {F_str}$\n$\\bf{{G(u,v)}} = {G_str}$',
             color='deepskyblue', fontsize=11, verticalalignment='top')

    #plt.show()
    plt.savefig(f"2_{pattern_description}.png", dpi=300)
    plt.close()

    return sol


run_simulation()

